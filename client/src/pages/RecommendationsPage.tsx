import React, { useState, useEffect } from 'react';
import {
  Lightbulb,
  ShieldAlert,
  AlertTriangle,
  CheckCircle2,
  Clock,
  Filter,
  ArrowRight,
  Info,
  Calendar,
} from 'lucide-react';
import { api } from '../services/api';
import { Recommendation, Assessment } from '../types';
import { useAuth } from '../context/AuthContext';

export const RecommendationsPage: React.FC = () => {
  const { role } = useAuth();
  const [recommendations, setRecommendations] = useState<Recommendation[]>([]);
  const [assessments, setAssessments] = useState<Assessment[]>([]);
  const [selectedAssessmentId, setSelectedAssessmentId] = useState<string>('all');
  const [priorityFilter, setPriorityFilter] = useState<string>('all');
  const [loading, setLoading] = useState(true);

  const canUpdate = role === 'administrator' || role === 'coordinator';

  async function loadData() {
    try {
      setLoading(true);
      const [recList, asmList] = await Promise.all([
        api.getRecommendations(),
        api.getAssessments(),
      ]);
      setRecommendations(recList);
      setAssessments(asmList);
    } catch (err) {
      console.error('Error loading recommendations:', err);
    } finally {
      setLoading(false);
    }
  }

  useEffect(() => {
    loadData();
  }, []);

  const handleUpdateStatus = async (id: string, newStatus: Recommendation['status']) => {
    try {
      await api.updateRecommendationStatus(id, newStatus);
      setRecommendations((prev) =>
        prev.map((r) => (r.id === id ? { ...r, status: newStatus } : r))
      );
    } catch (err) {
      alert((err as Error).message);
    }
  };

  const filtered = recommendations.filter((r) => {
    if (selectedAssessmentId !== 'all' && r.assessmentId !== selectedAssessmentId) return false;
    if (priorityFilter !== 'all' && r.priority !== priorityFilter) return false;
    return true;
  });

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
        <div>
          <div className="flex items-center gap-2">
            <h2 className="text-2xl font-bold text-slate-800 tracking-tight">
              Actionable Recommendations
            </h2>
            <span className="text-[11px] font-bold uppercase tracking-wider px-2 py-0.5 rounded bg-forest-100 text-forest-800 border border-forest-200">
              Rule-Based Engine
            </span>
          </div>
          <p className="text-xs text-slate-500 mt-0.5">
            Transparent algorithmic decision-support directives derived from probability calculations
          </p>
        </div>
      </div>

      {/* Disclaimers & Ethics */}
      <div className="p-4 bg-amber-50 border border-amber-200 rounded-xl text-amber-900 text-xs flex items-start gap-3">
        <Info className="w-5 h-5 text-amber-700 shrink-0 mt-0.5" />
        <div className="space-y-1">
          <strong className="font-bold text-amber-950">Civic Decision-Support Guidelines:</strong>
          <p className="leading-relaxed">
            Recommendations generated by GRAM SETU represent advisory decision-support suggestions for
            local administrative coordinators. They do not constitute mandatory statutory directives or
            guaranteed physical predictions. Coordinators must cross-reference directives with on-ground
            infrastructure checks.
          </p>
        </div>
      </div>

      {/* Filter Bar */}
      <div className="bg-white p-4 rounded-xl border border-slate-200 shadow-2xs flex flex-wrap items-center gap-3 text-xs">
        <div className="flex items-center gap-1.5 font-semibold text-slate-600">
          <Filter className="w-4 h-4 text-slate-400" />
          <span>Filters:</span>
        </div>

        {/* Assessment Filter */}
        <select
          value={selectedAssessmentId}
          onChange={(e) => setSelectedAssessmentId(e.target.value)}
          className="px-3 py-1.5 bg-slate-50 border border-slate-300 rounded-lg focus:outline-none focus:ring-1 focus:ring-forest-800 font-medium text-slate-700"
        >
          <option value="all">All Assessments</option>
          {assessments.map((a) => (
            <option key={a.id} value={a.id}>
              {a.villageName}: {a.assessmentName}
            </option>
          ))}
        </select>

        {/* Priority Filter */}
        <select
          value={priorityFilter}
          onChange={(e) => setPriorityFilter(e.target.value)}
          className="px-3 py-1.5 bg-slate-50 border border-slate-300 rounded-lg focus:outline-none focus:ring-1 focus:ring-forest-800 font-medium text-slate-700"
        >
          <option value="all">All Priorities</option>
          <option value="critical">Critical</option>
          <option value="high">High</option>
          <option value="medium">Medium</option>
          <option value="low">Low</option>
        </select>

        <span className="ml-auto text-slate-400 font-medium">
          Showing {filtered.length} active directives
        </span>
      </div>

      {/* Recommendations List */}
      <div className="space-y-4">
        {filtered.map((rec) => {
          const assessment = assessments.find((a) => a.id === rec.assessmentId);
          return (
            <div
              key={rec.id}
              className="bg-white rounded-xl border border-slate-200 p-5 shadow-2xs hover:shadow-md transition space-y-3"
            >
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-slate-100 pb-3">
                <div className="flex items-center gap-2.5">
                  <span
                    className={`text-[10px] font-bold uppercase tracking-wider px-2 py-0.5 rounded ${
                      rec.priority === 'critical'
                        ? 'bg-red-100 text-red-800 border border-red-200'
                        : rec.priority === 'high'
                        ? 'bg-amber-100 text-amber-800 border border-amber-200'
                        : 'bg-blue-100 text-blue-800'
                    }`}
                  >
                    {rec.priority} Priority
                  </span>
                  <h3 className="font-bold text-slate-900 text-base">{rec.title}</h3>
                </div>

                <div className="flex items-center gap-2">
                  <span className="text-[11px] text-slate-400">Status:</span>
                  <span
                    className={`text-[11px] font-bold uppercase px-2 py-0.5 rounded ${
                      rec.status === 'acted_upon'
                        ? 'bg-emerald-100 text-emerald-800'
                        : rec.status === 'acknowledged'
                        ? 'bg-blue-100 text-blue-800'
                        : 'bg-slate-100 text-slate-700'
                    }`}
                  >
                    {rec.status.replace('_', ' ')}
                  </span>
                </div>
              </div>

              <p className="text-xs sm:text-sm text-slate-700 leading-relaxed">
                {rec.description}
              </p>

              <div className="pt-2 flex flex-col sm:flex-row sm:items-center justify-between gap-3 text-xs text-slate-500 border-t border-slate-100">
                <div className="flex flex-wrap items-center gap-3">
                  <span className="font-mono text-[11px] bg-slate-50 px-2 py-0.5 rounded border border-slate-200 text-slate-600">
                    Rule Trigger: {rec.ruleTriggered}
                  </span>
                  {rec.actionDeadline && (
                    <span className="flex items-center gap-1 text-slate-500 text-[11px]">
                      <Calendar className="w-3.5 h-3.5 text-slate-400" />
                      Target Action Deadline: {rec.actionDeadline}
                    </span>
                  )}
                  {assessment && (
                    <span className="text-[11px] text-slate-500">
                      Village: <strong className="text-slate-700">{assessment.villageName}</strong>
                    </span>
                  )}
                </div>

                {/* Status Switcher for Authorized Users */}
                {canUpdate && (
                  <div className="flex items-center gap-1.5 self-end sm:self-auto">
                    {rec.status !== 'acknowledged' && rec.status !== 'acted_upon' && (
                      <button
                        onClick={() => handleUpdateStatus(rec.id, 'acknowledged')}
                        className="px-2.5 py-1 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-md font-semibold text-[11px] transition"
                      >
                        Acknowledge
                      </button>
                    )}
                    {rec.status !== 'acted_upon' && (
                      <button
                        onClick={() => handleUpdateStatus(rec.id, 'acted_upon')}
                        className="px-2.5 py-1 bg-forest-800 hover:bg-forest-900 text-white rounded-md font-semibold text-[11px] transition"
                      >
                        Mark as Acted Upon
                      </button>
                    )}
                    {rec.status === 'acted_upon' && (
                      <span className="text-emerald-700 font-semibold text-xs flex items-center gap-1">
                        <CheckCircle2 className="w-3.5 h-3.5" />
                        Completed
                      </span>
                    )}
                  </div>
                )}
              </div>
            </div>
          );
        })}
      </div>
    </div>
  );
};
